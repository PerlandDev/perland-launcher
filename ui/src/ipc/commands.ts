import { invoke } from '@tauri-apps/api/core';
import type {
  AccountsFile,
  AppInfo,
  ArtChoice,
  BrowsePlanRequest,
  ContentFile,
  ContentKind,
  DeepLink,
  IconChoice,
  ImageKind,
  InstallPlanView,
  InstallResult,
  Instance,
  InstanceArtData,
  InstanceListing,
  JavaTest,
  JoinPreview,
  LoaderKind,
  LoaderVersion,
  LocalMod,
  ManualProgress,
  McVersion,
  NewInstance,
  OpenTarget,
  PackAddRequest,
  PackContents,
  PackStatus,
  ProjectDetail,
  RunSnapshot,
  SearchPage,
  SearchRequest,
  ServerStatusView,
  Settings,
  UpdateState,
  VersionInfo,
} from './schema';

/** The only place the UI calls into Rust. A failed call rejects with a `LauncherError` object. */
export const commands = {
  appInfo: () => invoke<AppInfo>('app_info'),
  settingsGet: () => invoke<Settings>('settings_get'),
  settingsSet: (settings: Settings) => invoke<Settings>('settings_set', { settings }),
  updateStatus: () => invoke<UpdateState>('update_status'),
  updateCheck: () => invoke<UpdateState>('update_check'),
  updateRestart: () => invoke<null>('update_restart'),
  diagnosticsExport: (path: string) => invoke<string>('diagnostics_export', { path }),
  diagnosticsReveal: () => invoke<null>('diagnostics_reveal'),
  instancesList: () => invoke<InstanceListing>('instances_list'),
  instanceCreate: (request: NewInstance) => invoke<Instance>('instance_create', { request }),
  instanceUpdate: (instance: Instance) => invoke<Instance>('instance_update', { instance }),
  instanceRename: (id: string, name: string) => invoke<Instance>('instance_rename', { id, name }),
  instanceReorder: (ids: string[]) => invoke<InstanceListing>('instance_reorder', { ids }),
  instanceDelete: (id: string) => invoke<null>('instance_delete', { id }),
  catalogMinecraft: () => invoke<McVersion[]>('catalog_minecraft'),
  catalogLoaders: (kind: LoaderKind, mc: string) => invoke<LoaderVersion[]>('catalog_loaders', { kind, mc }),
  accountsList: () => invoke<AccountsFile>('accounts_list'),
  accountAddOffline: (name: string) => invoke<AccountsFile>('account_add_offline', { name }),
  accountSetActive: (uuid: string) => invoke<AccountsFile>('account_set_active', { uuid }),
  accountRemove: (uuid: string) => invoke<AccountsFile>('account_remove', { uuid }),
  play: (id: string, join = true) => invoke<null>('play', { id, join }),
  stop: (id: string) => invoke<null>('stop', { id }),
  runStates: () => invoke<RunSnapshot[]>('run_states'),
  logTail: (id: string) => invoke<string[]>('log_tail', { id }),
  modsList: (id: string) => invoke<LocalMod[]>('mods_list', { id }),
  modSetEnabled: (id: string, file: string, enabled: boolean) =>
    invoke<LocalMod[]>('mod_set_enabled', { id, file, enabled }),
  modsAdd: (id: string, paths: string[]) => invoke<LocalMod[]>('mods_add', { id, paths }),
  modRemove: (id: string, file: string) => invoke<LocalMod[]>('mod_remove', { id, file }),
  contentList: (id: string, kind: ContentKind) => invoke<ContentFile[]>('content_list', { id, kind }),
  contentRemove: (id: string, kind: ContentKind, file: string) =>
    invoke<ContentFile[]>('content_remove', { id, kind, file }),
  openFolder: (target: OpenTarget) => invoke<null>('open_folder', { target }),
  javaTest: (path: string) => invoke<JavaTest>('java_test', { path }),
  packAdd: (request: PackAddRequest) => invoke<Instance>('pack_add', { request }),
  playAnswer: (id: string, update: boolean) => invoke<null>('play_answer', { id, update }),
  packUpdate: (id: string) => invoke<null>('pack_update', { id }),
  packStatus: (id: string) => invoke<PackStatus>('pack_status', { id }),
  packContents: (id: string) => invoke<PackContents>('pack_contents', { id }),
  packSetOptional: (id: string, path: string, enabled: boolean) =>
    invoke<Instance>('pack_set_optional', { id, path, enabled }),
  manualImport: (id: string) => invoke<ManualProgress>('manual_import', { id }),
  instanceArt: (id: string) => invoke<InstanceArtData>('instance_art', { id }),
  instanceArtSet: (id: string, choice: ArtChoice) => invoke<Instance>('instance_art_set', { id, choice }),
  instanceIconSet: (id: string, choice: IconChoice) => invoke<Instance>('instance_icon_set', { id, choice }),
  deepLinkTake: () => invoke<DeepLink | null>('deep_link_take'),
  joinPreview: (link: string) => invoke<JoinPreview>('join_preview', { link }),
  joinAdd: (link: string) => invoke<Instance>('join_add', { link }),
  serverStatus: (id: string) => invoke<ServerStatusView>('server_status', { id }),
  serverRelink: (id: string, link: string) => invoke<Instance>('server_relink', { id, link }),
  quit: (stopGames: boolean) => invoke<null>('quit', { stopGames }),
  browseSearch: (request: SearchRequest) => invoke<SearchPage>('browse_search', { request }),
  browseCategories: (kind: ContentKind) => invoke<string[]>('browse_categories', { kind }),
  browseProject: (id: string) => invoke<ProjectDetail>('browse_project', { id }),
  browseVersions: (project: string, instance: string | null) =>
    invoke<VersionInfo[]>('browse_versions', { project, instance }),
  browseImage: (url: string, kind: ImageKind) => invoke<string>('browse_image', { url, kind }),
  browseInstalled: (id: string) => invoke<string[]>('browse_installed', { id }),
  browsePlan: (request: BrowsePlanRequest) => invoke<InstallPlanView>('browse_plan', { request }),
  browseInstall: (planId: string) => invoke<InstallResult>('browse_install', { planId }),
  openLink: (url: string) => invoke<null>('open_link', { url }),
};
